const KEY = 'vezbaj.lang';
function initialLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'sr' || q === 'en') return q;
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'sr' || saved === 'en') return saved;
  } catch (e) { /* private mode */ }
  // came from the English site?
  if (document.referrer.includes('/en/')) return 'en';
  return 'sr';
}

export let lang = initialLang();
const listeners = new Set();

export function t(key, params) {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.sr[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (k in params ? params[k] : `{${k}}`));
  return s;
}

export function setLang(l) {
  if (l !== 'sr' && l !== 'en') return;
  lang = l;
  try { localStorage.setItem(KEY, l); } catch (e) { /* private mode */ }
  applyStatic();
  for (const fn of listeners) fn(l);
}
export function onLangChange(fn) { listeners.add(fn); }

// texts written directly in the HTML
export function applyStatic(root = document) {
  document.documentElement.lang = lang === 'sr' ? 'sr-Latn' : 'en';
  document.title = t('doc.title');
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-href]')) el.setAttribute('href', t(el.dataset.i18nHref));
  for (const a of root.querySelectorAll('.lang button')) a.setAttribute('aria-pressed', String(a.dataset.lang === lang));
}
